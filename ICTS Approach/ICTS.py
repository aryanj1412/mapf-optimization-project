# --- Run experiments and save each result ---
def run_experiments():
    configs = [
        (2, 10),
        (5, 20),
        (8, 20),
        (10, 20),
        (12, 40)
    ]

    for num_agents, grid_size in configs:
        print(f"\n=== Running ICTS: {num_agents} agents on {grid_size}x{grid_size} grid ===")

        # Create grid with random obstacles
        obstacle_prob = 0.15 if grid_size <= 20 else 0.20
        grid = [[1 if random.random() < obstacle_prob else 0 for _ in range(grid_size)] for _ in range(grid_size)]

        starts, goals, taken = [], [], set()
        for _ in range(num_agents):
            while True:
                s = (random.randint(0, grid_size-1), random.randint(0, grid_size-1))
                g = (random.randint(0, grid_size-1), random.randint(0, grid_size-1))
                # ensure start/goal not on obstacle or already taken
                if grid[s[0]][s[1]] == 0 and grid[g[0]][g[1]] == 0 and s not in taken and g not in taken and s != g:
                    taken.add(s)
                    taken.add(g)
                    starts.append(s)
                    goals.append(g)
                    break

        agents = list(zip(starts, goals))
        sol = ict_search(grid, agents, max_paths_per_agent=3000)

        if sol:
            print(f"Found solution. Total cost = {sol['cost']}")
            filename = f"ICTS_{num_agents}agents_{grid_size}x{grid_size}.gif"
            visualize_and_save(grid, sol['paths'], starts, goals, filename)
        else:
            print("No solution found or search too costly.")


# --- MAIN ---
if __name__ == "__main__":
    run_experiments()